"""Repack skybox TGA assets losslessly into ASI resources. Standard Python only."""
from pathlib import Path
import argparse, hashlib, json, struct, zlib
parser=argparse.ArgumentParser(description=__doc__)
parser.add_argument('assets',type=Path,help='baloncuaga_skyboxes directory')
args=parser.parse_args();out=Path(__file__).resolve().parent
manifest=[];resources=['// Generated by pack_skyboxes.py. See LICENSE.txt.']
for sky_index,sky in enumerate(('sunny','night','sunset','overcast','aurora','space')):
    for face_index,face in enumerate(('rt','bk','lf','ft','up','dn','preview')):
        raw=(args.assets/sky/(face+'.tga')).read_bytes()
        if len(raw)<18 or len(raw)>32*1024*1024:raise ValueError('Invalid TGA size')
        name=f'{sky}_{face}.bsk';rid=4100+sky_index*7+face_index
        packed=b'BSK1'+struct.pack('<I',len(raw))+zlib.compress(raw,9)
        (out/name).write_bytes(packed);resources.append(f'{rid} RCDATA "{name}"')
        manifest.append(dict(id=rid,path=f'baloncuaga_skyboxes/{sky}/{face}.tga',file=name,bytes=len(raw),packed=len(packed),sha256=hashlib.sha256(raw).hexdigest()))
(out/'skyboxes.rc').write_text('\n'.join(resources)+'\n',encoding='ascii')
(out/'manifest.json').write_text(json.dumps(manifest,indent=2),encoding='utf-8')
print('Packed 42 resources,',sum(x['packed'] for x in manifest),'bytes')
